async function main() {
  console.log('[CustomerSeed] Starting...');
  console.log('  Branch ID:', BRANCH_ID);

  const areas   = await prisma.area.findMany({ where: { branchId: BRANCH_ID } });
  const areaIds = areas.map(a => a.id);
  const centers  = await prisma.center.findMany({ where: { areaId: { in: areaIds } } });
  const groups   = await prisma.group.findMany({ where: { centerId: { in: centers.map(c => c.id) } } });
  // Fetch ALL staff to avoid missing NULL branchId staff
  const staffList = await prisma.staff.findMany({});
  
  // Lookup maps
  const centerMap = new Map(centers.map(c => [parseInt(c.code!.replace(/\D/g, ''), 10), c]));
  const groupMap  = new Map(groups.map(g => [`${g.centerId}-${g.groupName}`, g.id]));
  
  // Staff phone fallback
  const AGENT_PHONES: Record<string, string> = {
    'STF0001': '9944533403', 'STF0002': '6383352231', 'STF0003': '7448889797',
    'STF0004': '6381194463', 'STF0005': '9080359113', 'STF0007': '7200473403',
    'STF0008': '8838587317', 'STF0009': '7708696683', 'STF0010': '8610319103',
  };
  const staffPhoneMap = new Map(staffList.map(s => [s.phone, s.id]));
  const staffNoMap    = new Map(staffList.map(s => [s.staffNo, s.id]));

  function getStaffId(staffNo: string): string | null {
    return staffNoMap.get(staffNo) ?? staffPhoneMap.get(AGENT_PHONES[staffNo] ?? '') ?? null;
  }

  const defaultArea = areas[0];

  let count = 0, skip = 0;
  for (const cust of CUSTOMERS) {
    const center = centerMap.get(cust.chitGroupCode);
    if (!center) { skip++; continue; }

    const areaId  = center.areaId || defaultArea.id;
    const groupId = groupMap.get(`${center.id}-${cust.partyGroupName}`) ?? null;
    const empId   = getStaffId(cust.agentStaffNo);

    const customer = await prisma.customer.upsert({
      where:  { customerNo: cust.customerNo },
      update: {},
      create: {
        customerNo:    cust.customerNo,
        name:          cust.name,
        mobile:        cust.mobile || '0000000000',
        phone:         cust.phone,
        address:       cust.address,
        dob:           cust.dob ? new Date(cust.dob) : null,
        maritalStatus: cust.maritalStatus,
        residenceType: cust.residenceType,
        occupation:    cust.occupation,
        fatherName:    cust.fatherName,
        motherName:    cust.motherName,
        familyMembers: cust.familyMembers,
        isActive:      cust.isActive,
        areaId, centerId: center.id, groupId, employeeId: empId,
      },
    });

    if (cust.id1No || cust.id2No) {
      await prisma.customerKyc.upsert({
        where:  { customerId: customer.id },
        update: {},
        create: {
          customerId:       customer.id,
          idProof1Type:     cust.id1Type, idProof1No: cust.id1No, idProof1Name: cust.id1Name,
          idProof2Type:     cust.id2Type, idProof2No: cust.id2No, idProof2Name: cust.id2Name,
        },
      });
    }

    if (cust.bankAccNo) {
      await prisma.customerBank.upsert({
        where:  { customerId: customer.id },
        update: {},
        create: {
          customerId:    customer.id,
          accountNumber: cust.bankAccNo, accountHolder: cust.bankAccHolder,
          ifsc:          cust.bankIfsc,  bankName: cust.bankName, branchName: cust.bankBranch,
        },
      });
    }

    if (cust.coName) {
      await prisma.customerCoApplicant.upsert({
        where:  { customerId: customer.id },
        update: {},
        create: { customerId: customer.id, name: cust.coName, relationship: cust.coRelationship },
      });
    }

    count++;
  }
  console.log(`[CustomerSeed] ✅ Done — ${count} customers seeded, ${skip} skipped`);
}

main().catch(console.error).finally(() => prisma.$disconnect());
